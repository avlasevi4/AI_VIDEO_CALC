import assert from 'node:assert/strict';
global.window = {};
await import('../js/preferences.js');
const prefs = window.AIVideoPreferences;
assert.deepEqual(prefs.normalize({}),{displayCurrency:'RUB',showDreaminaPlus:true});
assert.deepEqual(prefs.normalize({displayCurrency:'EUR',showDreaminaPlus:'false'}),{displayCurrency:'RUB',showDreaminaPlus:true});
assert.equal(prefs.formatMoney(80,{displayCurrency:'USD',usdRub:80}),'1,00 $');
assert.equal(prefs.formatMoney(-160,{displayCurrency:'USD',usdRub:80}),'-2,00 $');
assert.equal(prefs.formatMoney(80,{displayCurrency:'RUB',usdRub:0}),'80,00 ₽');
for(const rate of [0,-1,NaN,Infinity])assert.equal(prefs.formatMoney(80,{displayCurrency:'USD',usdRub:rate}),'—');
assert.equal(prefs.formatMoney(100/10500,{displayCurrency:'USD',usdRub:80},6),'0,000119 $');
assert.equal(prefs.showPrivateProvider(false,{showDreaminaPlus:true}),false);
assert.equal(prefs.showPrivateProvider(true,{showDreaminaPlus:false}),false);
assert.equal(prefs.showPrivateProvider(true,{}),true);
const snapshot={rub:80,usdRub:100,units:370};
const before=structuredClone(snapshot);
prefs.formatMoney(snapshot.rub,{displayCurrency:'USD',usdRub:80});
assert.deepEqual(snapshot,before,'Currency display must not rewrite historical cost or exchange rate');
console.log('Display preferences tests OK');
